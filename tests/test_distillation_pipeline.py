# --- paired evaluation and reasoning cost ---------------------------------
def paired(n=20, teacher_tokens=900, student_tokens=300):
    return [
        PairedRecord(
            example_id=f"e{i}", prompt_sha256="h", category="math",
            teacher={"total_output_tokens": teacher_tokens, "reasoning_tokens": 800,
                     "answer_tokens": 100, "correct": i % 5 != 0,
                     "latency_seconds": 2.0, "finish_reason": "stop"},
            student={"total_output_tokens": student_tokens, "reasoning_tokens": 200,
                     "answer_tokens": 100, "correct": i % 4 != 0,
                     "latency_seconds": 0.5, "finish_reason": "stop"},
        )
        for i in range(n)
    ]


def test_paired_summary_reports_both_sides_raw():
    summary = summarise_paired(paired())
    assert summary.teacher["accuracy"] == pytest.approx(0.8)
    assert summary.student["accuracy"] == pytest.approx(0.75)
    assert summary.teacher["median_reasoning_tokens"] == 800
    assert summary.student["median_reasoning_tokens"] == 200
    rendered = summary.render()
    assert "teacher" in rendered and "student" in rendered


def test_the_token_ratio_is_derived_not_primary():
    summary = summarise_paired(paired())
    assert summary.comparison["token_ratio"] == pytest.approx(300 / 900)
    assert summary.comparison["accuracy_delta"] == pytest.approx(-5.0)


def test_every_reported_metric_has_a_documented_formula():
    """No opaque efficiency score."""
    summary = summarise_paired(paired())
    for key in ("accuracy", "median_reasoning_tokens", "reasoning_share",
                "truncation_rate", "failure_rate"):
        assert key in METRIC_DEFINITIONS
    assert "accuracy_per_1k_reasoning_tokens" in summary.metric_definitions


def test_accuracy_per_reasoning_token_is_null_when_nothing_was_reasoned():
    """Dividing by zero reasoning is a different question, not a very good score."""
    records = [{"total_output_tokens": 10, "reasoning_tokens": 0, "answer_tokens": 10,
                "correct": True, "latency_seconds": 0.1}]
    assert summarise_side(records)["accuracy_per_1k_reasoning_tokens"] is None


def test_ungraded_examples_are_excluded_from_accuracy_not_counted_wrong():
    records = [
        {"total_output_tokens": 10, "reasoning_tokens": 0, "answer_tokens": 10,
         "correct": True, "latency_seconds": 0.1},
        {"total_output_tokens": 10, "reasoning_tokens": 0, "answer_tokens": 10,
         "correct": None, "latency_seconds": 0.1},
    ]
    summary = summarise_side(records)
    assert summary["n"] == 2
    assert summary["n_graded"] == 1
    assert summary["accuracy"] == 1.0


def test_truncation_is_measured_separately_from_failure():
    records = [
        {"total_output_tokens": 10, "reasoning_tokens": 0, "answer_tokens": 10,
         "correct": True, "latency_seconds": 0.1, "finish_reason": "length"},
        {"total_output_tokens": 10, "reasoning_tokens": 0, "answer_tokens": 10,
         "correct": True, "latency_seconds": 0.1, "finish_reason": "stop",
         "error": "boom"},
    ]
    summary = summarise_side(records)
    assert summary["truncation_rate"] == 0.5
    assert summary["failure_rate"] == 0.5


def test_token_budget_reports_coverage_alongside_accuracy():
    """A model answering 10% of prompts within budget and getting them right is not 100%."""
    records = [
        {"total_output_tokens": 100, "correct": True},
        {"total_output_tokens": 100, "correct": True},
        {"total_output_tokens": 5000, "correct": True},
        {"total_output_tokens": 5000, "correct": True},
    ]
    rows = {r["budget_tokens"]: r for r in accuracy_at_token_budget(records, (128,))}
    row = rows[128]
    assert row["coverage"] == 0.5
    assert row["accuracy_within_budget"] == 1.0
    assert row["accuracy_if_budget_enforced"] == 0.5


def test_the_sweep_table_is_ordered_by_effort():
    by_mode = {
        "xhigh": [{"total_output_tokens": 900, "reasoning_tokens": 800,
                   "answer_tokens": 100, "correct": True, "latency_seconds": 2.0}],
        "thinking_disabled": [{"total_output_tokens": 100, "reasoning_tokens": 0,
                               "answer_tokens": 100, "correct": False,
                               "latency_seconds": 0.2}],
        "low": [{"total_output_tokens": 300, "reasoning_tokens": 200,
                 "answer_tokens": 100, "correct": True, "latency_seconds": 0.6}],
    }
    rows = reasoning_sweep_table(by_mode)
    assert [r["mode"] for r in rows] == ["thinking_disabled", "low", "xhigh"]
    assert rows[0]["median_reasoning_tokens"] == 0


def test_per_category_breakdowns_survive_aggregation():
    records = paired(n=10)
    for record in records[:5]:
        record.category = "coding"
    summary = summarise_paired(records)
    assert set(summary.by_category) == {"math", "coding"}
    assert summary.by_category["coding"]["n"] == 5


def test_agreement_is_null_when_either_side_is_ungraded():
    record = PairedRecord(example_id="e", prompt_sha256="h",
                          teacher={"correct": True}, student={"correct": None})
    assert record.agreement() is None
