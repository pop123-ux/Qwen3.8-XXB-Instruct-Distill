"""The whole pipeline on CPU: prompts to teacher data to student loader to evaluation.

The point of the architecture under test is that the teacher and the student never need
to coexist. Generation runs once on hardware big enough for a 27B model and writes a
durable artifact; training reads that artifact weeks later on a free T4. These tests walk
that path end to end with a mock teacher, so the seams are exercised before any GPU time
is spent on them.

Also covered: every way the handoff can go wrong. A dataset that arrives short, edited,
duplicated, or generated by a different teacher than the one claimed.
"""

